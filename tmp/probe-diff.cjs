
const fs = require('fs')
const src = fs.readFileSync('E:/bqj/kuma/server/server.js', 'utf8').split('\n')
// editMonitor body: lines 801..1000 (1-based)
const body = src.slice(800, 1000).join('\n')
const reads = new Set()
for (const m of body.matchAll(/monitor\.([A-Za-z_][A-Za-z0-9_]*)/g)) reads.add(m[1])
const { io } = require('socket.io-client')
const s = io('http://127.0.0.1:3001', { timeout: 10000, reconnection: false })
const call = (ev, ...args) => new Promise((res, rej) => { const t = setTimeout(() => rej(new Error('timeout')), 15000); s.emit(ev, ...args, (r) => { clearTimeout(t); res(r) }) })
s.on('connect', async () => {
  await call('login', { username: 'admin', password: '' })
  const r = await call('getMonitor', 27)
  const keys = new Set(Object.keys(r.monitor))
  const missing = [...reads].filter((k) => !keys.has(k))
  console.log('editMonitor reads:', reads.size)
  console.log('missing in toJSON:', JSON.stringify(missing))
  s.close(); process.exit(0)
})
s.on('connect_error', (e) => { console.log('connect_error', e.message); process.exit(1) })
