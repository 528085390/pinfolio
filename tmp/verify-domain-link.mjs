import { chromium } from 'playwright-core'
const exe = 'C:\\Users\\you\\AppData\\Local\\ms-playwright\\chromium-1217\\chrome-win64\\chrome.exe'
const browser = await chromium.launch({ executablePath: exe })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5, locale: 'zh-CN' })
const page = await ctx.newPage()
const errors = []
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()) })
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
await page.goto('http://127.0.0.1:7788/', { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
await page.click('button[title="资产台账"]')
await page.waitForTimeout(900)
const card = page.locator('.asset-card', { hasText: 'example.com' }).first()
const link = card.locator('a.asset-link')
console.log('link href:', await link.getAttribute('href'))
console.log('link text:', (await link.innerText()).trim())
const cardBox = await card.boundingBox()
await page.screenshot({ path: 'tmp/shot-domain-card.png', clip: { x: cardBox.x - 8, y: cardBox.y - 8, width: cardBox.width + 16, height: cardBox.height + 16 } })
// 抽屉里「链接」字段是否同步
await card.click()
await page.waitForTimeout(900)
const urlInput = page.locator('.drawer input[placeholder="https://…"]').first()
console.log('drawer url value:', await urlInput.inputValue().catch(() => '(not found)'))
console.log('ERRORS:', errors.length ? JSON.stringify(errors) : 'none')
await browser.close()
