import { chromium } from 'playwright-core'
const exe = 'C:\\Users\\you\\AppData\\Local\\ms-playwright\\chromium-1217\\chrome-win64\\chrome.exe'
const browser = await chromium.launch({ executablePath: exe })
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5, locale: 'zh-CN' })
const page = await ctx.newPage()
const errors = []
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:7788/', { waitUntil: 'networkidle' })
await page.click('button[title="资产台账"]')
await page.waitForTimeout(900)
await page.screenshot({ path: 'E:/bqj/pinboard/tmp/shot-tagbar-renamed.png', clip: { x: 0, y: 0, width: 1440, height: 640 } })
const before = await page.locator('.asset-card .asset-name').allInnerTexts()
await page.locator('.tag-bar .chip', { hasText: '自建节点' }).first().click()
await page.waitForTimeout(700)
const after = await page.locator('.asset-card .asset-name').allInnerTexts()
console.log('all(' + before.length + ')=' + JSON.stringify(before))
console.log('filtered(' + after.length + ')=' + JSON.stringify(after))
await page.screenshot({ path: 'E:/bqj/pinboard/tmp/shot-tagbar-zijian.png', clip: { x: 0, y: 0, width: 1440, height: 760 } })
await page.locator('.tag-bar .chip', { hasText: '代理' }).first().click()
await page.waitForTimeout(700)
const proxy = await page.locator('.asset-card .asset-name').allInnerTexts()
console.log('代理(' + proxy.length + ')=' + JSON.stringify(proxy))
console.log('consoleErrors=' + JSON.stringify(errors))
await browser.close()