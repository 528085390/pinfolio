
import { chromium } from 'playwright-core'
const exe = 'C:\\Users\\you\\AppData\\Local\\ms-playwright\\chromium-1217\\chrome-win64\\chrome.exe'
const browser = await chromium.launch({ executablePath: exe })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 950 } })).newPage()
page.on('console', (m) => console.log('[console.' + m.type() + '] ' + m.text()))
page.on('pageerror', (e) => console.log('[pageerror] ' + e.message))
page.on('dialog', (d) => d.accept())
await page.goto('http://127.0.0.1:7788/', { waitUntil: 'networkidle' })
await page.click('button[title="资产台账"]')
await page.waitForTimeout(500)
await page.locator('.asset-card').first().click()
await page.waitForTimeout(600)
console.log('drawer open:', await page.locator('.drawer').count())
console.log('footer btns:', await page.locator('.drawer-foot button').allInnerTexts())
console.log('composer btns:', await page.locator('.drawer .composer button').allInnerTexts())
await page.fill('.drawer .composer textarea', '抽屉便签测试 #e2e标签')
await page.locator('.drawer .composer button').last().click()
await page.waitForTimeout(1000)
console.log('drawer open after add:', await page.locator('.drawer').count())
console.log('alert:', await page.locator('.drawer .alert').allInnerTexts())
console.log('drawer notes:', await page.locator('.drawer .note-body').count())
await page.screenshot({ path: 'tmp/dbg-drawer.png' })
await browser.close()
